"""Generate le_sig.h: the Live Editor build signature lec_native.dll accepts.

Reads FCLiveEditor.DLL offline (never loads it) and records, for each Lua C
API function the plugin calls, its RVA and the first SIG_LEN code bytes. The
plugin compares those bytes against the in-memory module before it calls
anything, so a different LE build disables the plugin instead of crashing.

RVAs were identified with REA (see Fc26 LE/re/LE_LUA_RUNTIME_SPEC.md):
  lua_gettop  0x51f450  ev_da879378...
  lua_settop  0x51f490  ev_7076135d...
  lua_load    0x521fb0  ev_815bcf29... (called by luaL_loadfilex)
  lua_pcallk  0x521d30  ev_a64eab61...

Usage:  python gen_le_sig.py <FCLiveEditor.DLL> [out.h]
        python gen_le_sig.py --check <FCLiveEditor.DLL> [le_sig.h]
"""
from __future__ import annotations

import hashlib
import struct
import sys
from pathlib import Path

LE_VERSION = "v26.3.6"
SHA256 = "0af955fcf7a34ec4055a11e18d3c621b4fa877cd6013776cfaa78a279b9308d9"
SIG_LEN = 24
FUNCS = (
    ("lua_gettop", 0x51F450),
    ("lua_settop", 0x51F490),
    ("lua_load", 0x521FB0),
    ("lua_pcallk", 0x521D30),
)


def _pe(data: bytes):
    pe_off = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe_off:pe_off + 4] != b"PE\0\0":
        raise ValueError("not a PE file")
    coff = pe_off + 4
    nsect = struct.unpack_from("<H", data, coff + 2)[0]
    timestamp = struct.unpack_from("<I", data, coff + 4)[0]
    opt_size = struct.unpack_from("<H", data, coff + 16)[0]
    opt = coff + 20
    if struct.unpack_from("<H", data, opt)[0] != 0x20B:
        raise ValueError("not PE32+")
    size_of_image = struct.unpack_from("<I", data, opt + 56)[0]
    sections = []
    for i in range(nsect):
        s = opt + opt_size + i * 40
        vsize, va, rawsize, rawptr = struct.unpack_from("<IIII", data, s + 8)
        sections.append((va, max(vsize, rawsize), rawptr, rawsize))
    return timestamp, size_of_image, sections


def _rva_bytes(data: bytes, sections, rva: int, n: int) -> bytes:
    for va, size, rawptr, rawsize in sections:
        if va <= rva < va + size:
            off = rawptr + (rva - va)
            if rva - va + n > rawsize:
                raise ValueError(f"RVA {rva:#x} runs past raw section data")
            return data[off:off + n]
    raise ValueError(f"RVA {rva:#x} not in any section")


def signature(dll: Path) -> dict:
    data = dll.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"FCLiveEditor.DLL sha256 {digest} is not {LE_VERSION} ({SHA256})")
    timestamp, size_of_image, sections = _pe(data)
    funcs = [(name, rva, _rva_bytes(data, sections, rva, SIG_LEN)) for name, rva in FUNCS]
    return {"timestamp": timestamp, "size_of_image": size_of_image, "funcs": funcs}


def render(sig: dict) -> str:
    lines = [
        "/* Generated by gen_le_sig.py from FCLiveEditor.DLL " + LE_VERSION + " — do not edit. */",
        f"/* sha256 {SHA256} */",
        "#pragma once",
        f'#define LE_SIG_VERSION "{LE_VERSION}"',
        f"#define LE_SIG_TIMESTAMP 0x{sig['timestamp']:08X}u",
        f"#define LE_SIG_SIZE_OF_IMAGE 0x{sig['size_of_image']:08X}u",
        f"#define LE_SIG_LEN {SIG_LEN}",
        "",
    ]
    for name, rva, raw in sig["funcs"]:
        body = ", ".join(f"0x{b:02X}" for b in raw)
        lines.append(f"#define LE_RVA_{name.upper()} 0x{rva:06X}u")
        lines.append(f"static const unsigned char LE_SIG_{name.upper()}[LE_SIG_LEN] = {{ {body} }};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if argv and argv[0] == "--check":
        dll = Path(argv[1])
        header = Path(argv[2]) if len(argv) > 2 else Path(__file__).with_name("le_sig.h")
        ok = header.read_text(encoding="utf-8") == render(signature(dll))
        print("LE SIGNATURE MATCHES" if ok else "LE SIGNATURE MISMATCH")
        return 0 if ok else 1
    dll = Path(argv[0])
    out = Path(argv[1]) if len(argv) > 1 else Path(__file__).with_name("le_sig.h")
    out.write_text(render(signature(dll)), encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
